import AppKit
import Carbon

/// Fn+, types a half-width comma. Any comma key event (also keypad ones) becomes 「、」 under Japanese input,
/// so while an input method is on, "," is pasted through the clipboard and the user's clipboard is put back.
@MainActor
final class CommaTyper {
    /// The target reads the clipboard asynchronously after ⌘V; the user's clipboard is restored after this.
    static let restoreDelay: TimeInterval = 0.6
    /// The user's clipboard taken before our own write, and the changeCount of that write.
    /// Presses within the delay (key repeat) keep the snapshot from the first one.
    private var pendingRestore: (items: [[NSPasteboard.PasteboardType: Data]], change: Int)?

    /// `flags`: the modifiers held with Fn+, (Fn already removed); they go with a plain comma key.
    func type(flags: CGEventFlags) {
        guard !ExcludedApps.shared.frontAppExcluded, let pid = NSWorkspace.shared.frontmostApplication?.processIdentifier else { return }
        if Self.inputMethodActive { paste(pid: pid) } else { sendKey(0x2B, flags: flags, pid: pid) }
    }

    /// True for Japanese (and other) input modes that convert punctuation; false for a plain layout such as ABC
    /// and for the input methods' Roman (英字) mode.
    static var inputMethodActive: Bool {
        guard let source = TISCopyCurrentKeyboardInputSource()?.takeRetainedValue() else { return false }
        func string(_ key: CFString) -> String? {
            TISGetInputSourceProperty(source, key).map { Unmanaged<CFString>.fromOpaque($0).takeUnretainedValue() as String }
        }
        if string(kTISPropertyInputSourceType) == (kTISTypeKeyboardLayout as String) { return false }
        let id = string(kTISPropertyInputModeID) ?? string(kTISPropertyInputSourceID) ?? ""
        return !id.hasSuffix(".Roman")
    }

    // Sent to the front app (not HID), so the Fn still held is not added to the event.
    private func sendKey(_ code: CGKeyCode, flags: CGEventFlags, pid: pid_t) {
        let source = CGEventSource(stateID: .privateState)
        for down in [true, false] {
            guard let event = CGEvent(keyboardEventSource: source, virtualKey: code, keyDown: down) else { return }
            event.setIntegerValueField(.eventSourceUserData, value: NumpadTap.marker)
            event.flags = flags
            event.postToPid(pid)
        }
    }

    private func paste(pid: pid_t) {
        let pasteboard = NSPasteboard.general
        let saved = takeSnapshot()
        pasteboard.clearContents()
        // nspasteboard.org markers: clipboard history apps skip transient, app-generated contents.
        let item = NSPasteboardItem()
        item.setString(",", forType: .string)
        for marker in ["org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"] { item.setData(Data(), forType: NSPasteboard.PasteboardType(marker)) }
        guard pasteboard.writeObjects([item]) else { restore(saved); NSSound.beep(); return }
        sendKey(9, flags: .maskCommand, pid: pid)   // ⌘V
        restoreLater(saved, after: pasteboard.changeCount)
    }

    // MARK: - Clipboard (from PasteMatchStyle's PlainPaster)

    /// Every representation of the user's clipboard, or the one already saved when our own write is still on it.
    private func takeSnapshot() -> [[NSPasteboard.PasteboardType: Data]] {
        let pasteboard = NSPasteboard.general
        if let pendingRestore, pendingRestore.change == pasteboard.changeCount { return pendingRestore.items }
        return (pasteboard.pasteboardItems ?? []).map { item in
            var saved: [NSPasteboard.PasteboardType: Data] = [:]
            for type in item.types { if let data = item.data(forType: type) { saved[type] = data } }
            return saved
        }
    }
    private func restore(_ items: [[NSPasteboard.PasteboardType: Data]]) {
        let pasteboard = NSPasteboard.general
        pendingRestore = nil
        pasteboard.clearContents()
        let objects = items.map { saved -> NSPasteboardItem in
            let item = NSPasteboardItem()
            for (type, data) in saved { item.setData(data, forType: type) }
            return item
        }
        if !objects.isEmpty { pasteboard.writeObjects(objects) }
    }
    private func restoreLater(_ items: [[NSPasteboard.PasteboardType: Data]], after change: Int) {
        pendingRestore = (items, change)
        DispatchQueue.main.asyncAfter(deadline: .now() + Self.restoreDelay) { [weak self] in
            // A later paste or a new copy by the user has already replaced the clipboard (B10).
            guard let self, NSPasteboard.general.changeCount == change else { return }
            self.restore(items)
        }
    }
}
