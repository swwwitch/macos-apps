import AppKit

/// One rewrite shown in the main window. Kept in memory only, never written to disk.
struct HistoryEntry: Identifiable {
    let id = UUID()
    let date: Date
    let rules: [String]
    let before: String
    let after: String
}

/// Watches the general pasteboard. macOS has no change notification, so this compares changeCount
/// on a light timer (a number read, no content read) and reads the text only after a change.
@MainActor final class ClipboardMonitor {
    private let pasteboard = NSPasteboard.general
    private var lastChange: Int
    private var timer: Timer?
    /// Content marked secret or temporary by password managers and other apps (nspasteboard.org).
    static let skippedTypes: Set<String> = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword"]
    static let maxLength = 200_000
    var onChange: ((String, NSRunningApplication?) -> Void)?

    init() { lastChange = pasteboard.changeCount }

    func start() {
        guard timer == nil else { return }
        lastChange = pasteboard.changeCount  // Content copied while stopped is left as is.
        let timer = Timer(timeInterval: 0.3, repeats: true) { [weak self] _ in MainActor.assumeIsolated { self?.poll() } }
        timer.tolerance = 0.15
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }
    func stop() { timer?.invalidate(); timer = nil }

    private func poll() {
        let count = pasteboard.changeCount
        guard count != lastChange else { return }
        lastChange = count
        let types = Set((pasteboard.types ?? []).map(\.rawValue))
        guard types.isDisjoint(with: Self.skippedTypes), let text = pasteboard.string(forType: .string), !text.isEmpty, text.count <= Self.maxLength else { return }
        onChange?(text, NSWorkspace.shared.frontmostApplication)
    }

    /// Replaces the clipboard with plain text, unless something newer was copied since `expected` (B10).
    @discardableResult
    func write(_ text: String, ifStill expected: Int? = nil) -> Bool {
        if let expected, pasteboard.changeCount != expected { return false }
        pasteboard.clearContents()
        pasteboard.setString(text, forType: .string)
        lastChange = pasteboard.changeCount
        return true
    }
    var changeCount: Int { pasteboard.changeCount }
}
